// 문이 열려 있는 동안, 집중장치 명령과 무관하게 게이트웨이가 스스로 리더를 순회하며
// "빈 자리에 스마트폰이 새로 놓였는지"를 감지해서 확인 부저를 울린다. RS485/서버와
// 완전히 무관한 순수 로컬 로직이다 — 네트워크(집중장치와의 통신)가 끊긴 상태에서도
// 거치 확인음은 나야 한다는 요구사항 때문에, rs485_link의 'R' 명령 응답 경로와는
// 별개로 동작한다.
//
// - 새로 놓임(비어있다가 인식됨): 부저 O
// - 빼감(있다가 안 잡힘): 부저 X (가져갈 때 소리 나면 안 된다는 요구사항)
// - 문이 닫혀 있는 동안은 스캔하지 않는다(어차피 손이 안 닿음) — 마지막으로 알던 상태를
//   그대로 유지하고, 문이 다시 열리면 이어서 스캔한다(원래 있던 폰을 "새로 놓임"으로
//   오인해서 다시 삑 소리 내지 않도록).
//
// 재부팅 시 캐시는 항상 전부 비어있는 상태로 시작한다(EEPROM 등에 이전 상태를 저장해서
// 복원하지 않음) — 확인 요청: 문이 열려 있는 상태로 재부팅됐는데 거치대에 폰이 있으면
// 부저가 울리는 게 맞는 동작이다(2026-09-02). "재부팅 전에도 있었으니 조용해야 한다"는
// 판단을 하려면 상태를 영구 저장해야 하는데, 그럴 필요가 없다고 확정됨.

void presenceWatch_setup();

// loop()에서 매번 호출 — 내부에서 문이 열려 있는지 직접 확인하고(door_lock 참조),
// 열려 있을 때만 리더를 1개씩 순회 스캔한다(라운드로빈, loop() 한 바퀴를 짧게 유지).
void presenceWatch_loop();

